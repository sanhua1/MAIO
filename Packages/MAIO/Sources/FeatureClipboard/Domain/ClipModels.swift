import Foundation

/// 条目类型（决定列表里怎么显示）。
enum ClipKind: String, Codable, Sendable, CaseIterable {
    case text
    case richText
    case image
    case files

    var title: String {
        switch self {
        case .text: "文字"
        case .richText: "富文本"
        case .image: "图片"
        case .files: "文件"
        }
    }
}

/// 剪贴板上的一份数据：第几个剪贴板条目（NSPasteboardItem）的哪种类型（UTI）。
/// 同一次复制可能有多个条目（例如复制多个文件），写回时按 itemIndex 还原。
struct Representation: Sendable, Equatable {
    var itemIndex: Int
    var type: String
    var data: Data
}

/// 一次复制的完整内容。
struct ClipPayload: Sendable, Equatable {
    var representations: [Representation]

    var byteSize: Int64 {
        Int64(representations.reduce(0) { $0 + $1.data.count })
    }

    func data(_ type: String) -> Data? {
        representations.first { $0.type == type }?.data
    }

    var types: Set<String> {
        Set(representations.map(\.type))
    }

    /// 纯文本内容（如果有）
    var plainText: String? {
        data(PasteType.plainText).flatMap { String(bytes: $0, encoding: .utf8) }
    }

    /// 所有文件路径（按条目顺序）
    var fileURLs: [URL] {
        representations.filter { $0.type == PasteType.fileURL }.compactMap { representation in
            String(bytes: representation.data, encoding: .utf8).flatMap(URL.init(string:))
        }
    }

    var kind: ClipKind {
        let types = types
        if types.contains(PasteType.fileURL) {
            return .files
        }
        if plainText?.isEmpty == false {
            return types.contains(PasteType.rtf) || types.contains(PasteType.html) ? .richText : .text
        }
        if types.contains(PasteType.png) || types.contains(PasteType.tiff) {
            return .image
        }
        return .text
    }

    /// 列表里显示的一行摘要
    var summary: String {
        switch kind {
        case .files:
            let names = fileURLs.map(\.lastPathComponent)
            return names.count > 1 ? "\(names[0]) 等 \(names.count) 个文件" : names.first ?? "文件"
        case .image:
            return "图片"
        case .text, .richText:
            return ClipText.summary(plainText ?? "")
        }
    }

    /// "内容是否相同"的依据（不管格式）：文字比较纯文本，文件比较路径，图片比较图片数据。
    /// 同一段文字从不同 App 复制，附带的格式（RTF、HTML）往往不同，完整哈希对不上，但用户看来是重复的。
    var contentKey: Data? {
        switch kind {
        case .files:
            return Data(("files\n" + fileURLs.map(\.path).joined(separator: "\n")).utf8)
        case .image:
            return data(PasteType.png).map { Data("png\n".utf8) + $0 } ?? data(PasteType.tiff).map { Data("tiff\n".utf8) + $0 }
        case .text, .richText:
            return plainText.map { Data(("text\n" + ClipText.normalized($0)).utf8) }
        }
    }

    /// 只保留纯文本（⇧回车：去掉格式粘贴）
    var plainTextOnly: ClipPayload? {
        guard let text = data(PasteType.plainText) else { return nil }
        return ClipPayload(representations: [Representation(itemIndex: 0, type: PasteType.plainText, data: text)])
    }
}

/// 剪贴板类型（UTI）常量。Domain 不 import AppKit，所以不用 NSPasteboard.PasteboardType。
enum PasteType {
    static let plainText = "public.utf8-plain-text"
    static let rtf = "public.rtf"
    static let html = "public.html"
    static let png = "public.png"
    static let tiff = "public.tiff"
    static let fileURL = "public.file-url"
    // 参考：references/Maccy/Maccy/Clipboard.swift（supportedTypes）
    /// 只保存这些类型（参考 Maccy：其他私有类型往往体积巨大且无法跨 App 使用）
    static let persisted: Set<String> = [plainText, rtf, html, png, tiff, fileURL]
    /// MAIO 自己写入剪贴板时加的标记，监听时跳过
    static let maioMarker = "app.maio.clipboard.marker"
    /// 恢复剪贴板时的通用标记（nspasteboard.org 约定），监听时跳过
    static let restored = "org.nspasteboard.RestoredType"
    /// 系统自动生成的内容（nspasteboard.org 约定），监听时跳过
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
}

/// 一条历史记录的元数据（列表显示用，不含完整数据）。
struct ClipItem: Sendable, Equatable, Identifiable {
    var id: Int64
    var kind: ClipKind
    var summary: String
    var sourceBundleID: String?
    var createdAt: Date
    var lastUsedAt: Date
    var byteSize: Int64
    var isPinned: Bool
    /// 有缩略图（图片条目，或者复制的图片文件）
    var hasThumbnail: Bool = false
}

enum ClipText {
    /// 比较内容时忽略的差别：换行符（\r\n、\r 统一成 \n）、首尾空白。
    /// 终端里选中的文字，同一段有时带 \r\n、有时带 \n，首尾还可能多一个空格。
    static func normalized(_ text: String) -> String {
        text.replacingOccurrences(of: "\r\n", with: "\n")
            .replacingOccurrences(of: "\r", with: "\n")
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// 新复制的文字是不是"同一次选择的延续"：一段包含另一段。
    /// 终端"选中即复制"时，拖动选区的过程中每变一下就复制一次，产生一串长短不一的版本。
    static func isSelectionGrowth(old: String, new: String) -> Bool {
        let old = normalized(old)
        let new = normalized(new)
        guard !old.isEmpty, !new.isEmpty else { return false }
        return new.contains(old) || old.contains(new)
    }

    /// 合并空白、截断，用于一行显示
    static func summary(_ text: String, limit: Int = 300) -> String {
        let collapsed = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return collapsed.count > limit ? String(collapsed.prefix(limit)) + "…" : collapsed
    }
}
