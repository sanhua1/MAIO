import AppKit

// 参考：references/Maccy/Maccy/Clipboard.swift（checkForChangesInPasteboard）
/// 监听剪贴板变化。系统没有变化通知，只能定时检查 changeCount（Maccy 等都是这样做的）。
/// 跳过：MAIO 自己写入的内容、恢复剪贴板时写回的内容、系统自动生成的内容。
/// 不会跳过密码管理器标记为"隐藏"的内容（用户明确要求，见 ADR-0010）。
@MainActor
final class PasteboardMonitor {
    static let interval: TimeInterval = 0.3
    /// 单次复制超过这个大小就不记录（避免误复制超大图片撑满存储）
    static let maxPayloadBytes = 200_000_000

    struct Options {
        var recordRichText = true
        var recordImages = true
        var recordFiles = true
    }

    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    private var timer: Timer?
    private let onCopy: (ClipPayload, String?) -> Void
    var options = Options()

    init(onCopy: @escaping (ClipPayload, String?) -> Void) {
        self.onCopy = onCopy
        changeCount = pasteboard.changeCount
    }

    func start() {
        stop()
        changeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: Self.interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// MAIO 自己写剪贴板后调用，避免把自己写入的内容当成新的复制
    func skipCurrent() {
        changeCount = pasteboard.changeCount
    }

    private func check() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        let allTypes = Set((pasteboard.types ?? []).map(\.rawValue))
        let skipped: Set = [PasteType.maioMarker, PasteType.restored, PasteType.autoGenerated]
        guard allTypes.isDisjoint(with: skipped),
              let payload = read(), !payload.representations.isEmpty,
              payload.byteSize <= Self.maxPayloadBytes
        else { return }
        onCopy(payload, NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
    }

    private func read() -> ClipPayload? {
        var representations: [Representation] = []
        for (index, item) in (pasteboard.pasteboardItems ?? []).enumerated() {
            for type in item.types where isWanted(type.rawValue) {
                guard let data = item.data(forType: type) else { continue }
                representations.append(Representation(itemIndex: index, type: type.rawValue, data: data))
            }
        }
        var payload = ClipPayload(representations: representations)
        // 只有空白的文字不记录
        if payload.kind == .text, payload.plainText?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true {
            return nil
        }
        // 文件条目只保留路径和文件名文字，丢掉附带的图标图片等
        if payload.kind == .files {
            payload.representations.removeAll { $0.type != PasteType.fileURL && $0.type != PasteType.plainText }
        }
        return payload
    }

    private func isWanted(_ type: String) -> Bool {
        guard PasteType.persisted.contains(type) else { return false }
        switch type {
        case PasteType.rtf, PasteType.html: return options.recordRichText
        case PasteType.png, PasteType.tiff: return options.recordImages
        case PasteType.fileURL: return options.recordFiles
        default: return true
        }
    }
}
