/// 滚动设置的说明文字（设置页 ⓘ 按钮中显示）。
enum ScrollHelp {
    static let zoom = """
    按住修饰键（默认 ⌘）再拨滚轮，MAIO 会模拟触控板的双指捏合：往前拨放大，往后拨缩小。看图片、PDF、网页、地图时和触控板一样平滑缩放。

    只对鼠标滚轮生效，触控板照常。打开后，App 自己的"修饰键 + 滚轮"功能（例如有的 App 用 ⌘ + 滚轮缩放）会被替换；不想要时可以换成 ⌥ 或 ⌃，或者关掉这项。

    个别 App 不支持捏合缩放（例如终端），在里面不会有反应。

    MAIO 自己的窗口不受影响：在贴图上 ⌘ + 滚轮仍然是调透明度。
    """

    static let zoomSpeed = "每格滚轮缩放多少。1.0× 约为每格 5%。"

    static let reverse = """
    反转鼠标滚轮的方向。

    系统开着"自然滚动"时，鼠标滚轮和触控板方向相同（向下拨滚轮，页面向上走）。打开这项后，鼠标恢复成 Windows 那样的传统方向，触控板仍保持自然滚动。
    """

    static let smooth = """
    把一格一格的滚轮滚动变成连续的动画，像触控板一样顺滑。

    关闭后，MAIO 只负责反转方向，滚动距离完全按系统原样。下方的"跨度"和"倍率"只在开启平滑时生效。
    """

    static let step = """
    每次滚动至少走多少像素（保底值）。

    慢慢拨一格时，滚轮的原始距离通常只有 10 像素左右，会被补到这个值；快速拨动时原始距离已经够大，这项就不起作用。

    调大：慢慢滚时每格走得更多。
    """

    static let speed = """
    把每次滚动的距离乘上这个倍数，快滚、慢滚一起变远或变近。

    例：默认跨度 33.6、倍率 2.7
    • 慢慢滚一格：原始 10 → 补到 33.6 → ×2.7 ≈ 91 像素
    • 快速拨一下：原始 80 → 不补 → ×2.7 ≈ 216 像素

    一格滚太远：调小倍率。
    """

    static let duration = """
    这段距离花多长时间滚完（动画的快慢），不改变总距离。

    调小：停得更快、更利落。
    调大：拖尾更长、更顺滑。
    """

    static let tuning = """
    • 一格滚太远 / 太近 → 调"速度倍率"
    • 只是慢慢滚时每格太少，快滚时正好 → 调大"滚动跨度"
    • 距离合适，只想让动画更利落或更顺滑 → 调"平滑时长"
    """

    static let shift = """
    按住 ⇧ 再滚动鼠标滚轮时，变成左右滚动（同样是平滑的）。

    按住 ⌘、⌃、⌥ 时 MAIO 不做平滑，保证 ⌘ + 滚轮缩放这类操作正常。
    """

    static let exceptions = """
    在这些 App 里关闭平滑和 / 或反转，适合游戏、远程桌面、绘图软件等。

    以鼠标所指的 App 为准，而不是前台 App：鼠标停在哪个窗口上，就按哪个 App 的规则处理。
    """
}
